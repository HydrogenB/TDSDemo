// Helper function to get events by country and year range
export const getEventsByCountry = (countryCode: string, startYear?: number, endYear?: number): HistoricalEvent[] => {
  return historicalEvents.filter(event => {
    const matchCountry = event.country_code === countryCode;
    const matchStart = startYear ? event.year_ad >= startYear : true;
    const matchEnd = endYear ? event.year_ad <= endYear : true;
    return matchCountry && matchStart && matchEnd;
  }).sort((a, b) => a.year_ad - b.year_ad);
};

// Get all events for a specific year
export const getEventsByYear = (year: number): HistoricalEvent[] => {
  return historicalEvents.filter(event => event.year_ad === year);
};

// Get events near a specific year (within range)
export const getEventsNearYear = (year: number, range: number = 5): HistoricalEvent[] => {
  return historicalEvents.filter(event =>
    event.year_ad >= year - range && event.year_ad <= year + range
  ).sort((a, b) => a.year_ad - b.year_ad);
};
